export function getRolesForBusiness(businessName: string): string[] {
  if (!businessName) return [];
  const exact = BUSINESS_ORGANIZATIONS_CATALOG[businessName];
  if (exact && exact.length > 0) return exact;

  // Fuzzy match
  const lower = businessName.toLowerCase();
  for (const [key, roles] of Object.entries(BUSINESS_ORGANIZATIONS_CATALOG)) {
    if (key.toLowerCase().includes(lower) || lower.includes(key.toLowerCase())) {
      return roles;
    }
  }
  return [];
}
